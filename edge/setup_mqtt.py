"""Generate random local credentials without printing them or shell interpolation."""
import secrets
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    env_file = ROOT / ".env.local"
    target = ROOT / ".runtime" / "mqtt"
    if env_file.exists() or (target / "passwords").exists():
        raise SystemExit("Existing credentials found; keep them or rotate manually. Nothing overwritten.")
    target.mkdir(parents=True, exist_ok=True)
    simulator = secrets.token_urlsafe(32)
    gateway = secrets.token_urlsafe(32)
    subprocess.run([
        "docker", "run", "--rm", "-i", "--mount", f"type=bind,source={target},target=/secrets",
        "eclipse-mosquitto:2", "sh", "-c",
        "umask 077; cat > /secrets/passwords; mosquitto_passwd -U /secrets/passwords; chmod 644 /secrets/passwords",
    ], input=f"simulator:{simulator}\ngateway:{gateway}\n", text=True, check=True)
    template = (ROOT / ".env.example").read_text()
    template = template.replace("MQTT_SIMULATOR_PASSWORD=<generated by edge/setup_mqtt.py>", f"MQTT_SIMULATOR_PASSWORD={simulator}")
    template = template.replace("MQTT_GATEWAY_PASSWORD=<generated by edge/setup_mqtt.py>", f"MQTT_GATEWAY_PASSWORD={gateway}")
    env_file.write_text(template, encoding="utf-8")
    print("Created ignored .env.local and hashed MQTT passwords. Add the IoT Hub DEVICE connection string privately.")


if __name__ == "__main__":
    main()
